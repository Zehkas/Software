CREATE TABLE USUARIOS (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    apellido VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) UNIQUE NOT NULL,
    password VARCHAR2(255) NOT NULL,
    rol NUMBER -- 1 admin, 0 usuario
);

CREATE TABLE PRESETS (
    id_preset NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) UNIQUE NOT NULL,
    descripcion VARCHAR2(500),
    categoria VARCHAR2(50),
    precio NUMBER(10, 2) NOT NULL,
    imagen_url VARCHAR2(255),
    estado NUMBER -- 1 activo, 0 desactivado
);


CREATE TABLE PEDIDOS (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL,
    fecha_pedido DATE DEFAULT SYSDATE,
    monto_total NUMBER(10, 2),
    tipo_pedido VARCHAR2(20),
    estado_pedido VARCHAR2(20),
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIOS(id_usuario)
);


CREATE TABLE DETALLE_PEDIDO (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL,
    id_preset NUMBER NOT NULL,
    precio_unitario NUMBER(10, 2),
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES PEDIDOS(id_pedido),
    CONSTRAINT fk_detalle_preset FOREIGN KEY (id_preset) REFERENCES PRESETS(id_preset)
);
